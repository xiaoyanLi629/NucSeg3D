NUM = r"([+-]?\d+\.\d+)"


def judge(lo, hi):
    if lo > 0:
        return "better"
    if lo >= -0.02:
        return "non-inf."
    if hi < 0:
        return "worse"
    return "inconcl."


def per_dataset(logname):
    """Return {metric: [(ds, n, s1, d2, base, d_2d, lo, hi, d_b, lo_b, hi_b) or (ds, n, s1, d2, base, None...)]}."""
    lines = (D / logname).read_text(encoding="utf-8").splitlines()
    out, cur = {}, None
    pat = re.compile(r"^\s+(\w+)\s+n=\s*(\d+)\s+" + NUM + r" \| " + NUM + r" \| " + NUM + r"\s+(.*)$")
    for ln in lines:
        if "-- F1@0.5" in ln:
            cur = "f05"; out[cur] = []
        elif "-- F1@0.7" in ln:
            cur = "f07"; out[cur] = []
        m = pat.match(ln)
        if m and cur:
            ds, n, s1, d2, b, rest = m.groups()
            iv = re.findall(NUM + r" \[" + NUM + r", " + NUM + r"\]", rest)
            if len(iv) >= 2:
                (a, lo, hi), (c, lo2, hi2) = iv[:2]
                out[cur].append((ds, int(n), float(s1), float(d2), float(b), float(a), float(lo), float(hi),
                                 float(c), float(lo2), float(hi2)))
            else:
                out[cur].append((ds, int(n), float(s1), float(d2), float(b)) + (None,) * 6)
    return out


def macro_lines(logname):
    """Seed-level macro and paired differences printed by s5_stats.py."""
    txt = (D / logname).read_text(encoding="utf-8")
    res = []
    metric = None
    for ln in txt.splitlines():
        if "-- F1@0.5" in ln:
            metric = "F1@0.5"
        elif "-- F1@0.7" in ln:
            metric = "F1@0.7"
        m = re.match(r"^\s+宏平均（(.*?)）S1 (\d\.\d+).*?二维 (\d\.\d+).*?原版 (\d\.\d+)", ln)
        if m:
            label = m.group(1)
            res.append([metric, label, float(m.group(2)), float(m.group(3)), float(m.group(4))])
        m2 = re.match(r"^\s+S1−二维 逐种子 (.*?)；均值 " + NUM + r"，SD (\d\.\d+)，(\S+?)（", ln)
        if m2 and res:
            seeds = [s.strip() for s in m2.group(1).split("、")]
            res[-1] += [seeds, float(m2.group(2)), float(m2.group(3)), m2.group(4) == "通过确认"]
    return res


def tex_table(caption, label, cols, header, rows, size="\\scriptsize"):
    s = ["\\begin{table}[p]", "\\caption{" + caption + "}\\label{" + label + "}", size,
         "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}" + cols + "@{}}", "\\toprule", header + " \\\\", "\\midrule"]
    s += [" & ".join(r) + " \\\\" for r in rows]
    s += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
    return "\n".join(s)


def f3(x):
    return f"{x:.3f}"


def sg(x):
    return f"{x:+.3f}".replace("-", "$-$")


