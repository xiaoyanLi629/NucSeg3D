"""Generate Supplementary Tables (LaTeX) from the result snapshots in ../data_snapshot/.

Every number in supp_tables.tex is parsed from a snapshot file (copied from hostA on 2026-11-08,
md5-checked against the server for the main logs); nothing is typed by hand except table headers.
Per-dataset judgements are recomputed from the printed bootstrap intervals with the renamed categories:
better (lower bound > 0), non-inferior (lower bound >= -0.02), worse (upper bound < 0), inconclusive (otherwise).

Usage: python3 -I scripts/make_supp_tables.py   (run from paper/)
"""
