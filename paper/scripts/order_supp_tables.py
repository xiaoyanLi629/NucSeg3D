"""Assemble Supplementary Tables in order of first citation in main.tex (NC: number items in citation order).

Reads table blocks from supp_tables_manual.tex and the generated supp_tables*.tex files, orders them by the first
\\ref{S-<label>} in main.tex, appends any table never cited in main.tex, and writes supp_tables_ordered.tex.
Run after scripts/make_supp_tables.py and before compiling supplementary.tex.
Usage (from paper/): python3 -I scripts/order_supp_tables.py"""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent.parent
files = ["supp_tables_manual.tex", "supp_tables.tex", "supp_tables_g2g5.tex", "supp_tables_vox.tex", "supp_tables_r3.tex", "supp_tables_eo.tex"]  # eo: scripts/make_supp_table_eo.py
blocks = {}
for f in files:
    txt = (here / f).read_text(encoding="utf-8")
    found = re.findall(r"\\begin\{table\}\[p\].*?\\end\{table\}", txt, re.S)
    found += [x.strip() for x in re.findall(r"%%LT-BEGIN\n(.*?)\n%%LT-END", txt, re.S)]  # long tables spanning pages
    for b in found:
        lab = re.search(r"\\label\{([^}]*)\}", b).group(1)
        if lab in blocks:
            sys.exit("duplicate table label " + lab)
        blocks[lab] = b
main = (here / "main.tex").read_text(encoding="utf-8")
order = []
for lab in re.findall(r"\\ref\{S-(stab:[^}]*)\}", main):
    if lab not in order:
        order.append(lab)
missing = [l for l in order if l not in blocks]
if missing:
    sys.exit("cited but not found: " + ", ".join(missing))
rest = [l for l in blocks if l not in order]
out = ["%% GENERATED by scripts/order_supp_tables.py -- do not edit by hand."]
out += [blocks[l] for l in order + rest]
txt = "\n\n".join(out) + "\n"
# 2026-11-11: tables are only ever shrunk to the text width, never enlarged (narrow tables such as L2 were scaled up to
# ~11 pt); one font size for all tables
txt = txt.replace("\\resizebox{\\textwidth}{!}{", "\\adjustbox{max width=\\textwidth}{").replace("\\tiny", "\\scriptsize")
(here / "supp_tables_ordered.tex").write_text(txt, encoding="utf-8")
print("ordered:", ", ".join(order), "| not cited in main:", ", ".join(rest) or "none")
