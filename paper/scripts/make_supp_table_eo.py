"""Build supp_tables_eo.tex (Supplementary Table stab:eo, encoder-only control) from data_snapshot/eo_analysis_part2_local.log
(read-only copy of hostA:$NUCSEG3D_SCRATCH/nc/gpu/eo/eo_analysis_part2_local.log). Values are shown exactly as in the log (4 decimals),
so no second rounding is introduced. Usage (from paper/): python3 -I scripts/make_supp_table_eo.py"""
import pathlib, re
here = pathlib.Path(__file__).resolve().parent.parent
log = (here / "data_snapshot" / "eo_analysis_part2_local.log").read_text(encoding="utf-8").splitlines()
GRP = {"三视图10套": ("three-view", "10"), "单视图3套": ("single-view", "3"), "12套(去mesospim)": ("all", "12"), "13套": ("all", "13")}
ORDER = ["三视图10套", "单视图3套", "12套(去mesospim)", "13套"]
def pm(s):
    return s.replace("-", "$-$").replace("±", " $\\pm$ ")
def diff(txt, key):
    m = re.search(re.escape(key) + r" (\S+?±\S+)( ✓| \(负，\|均值\|>2SD\))?", txt)
    v = pm(m.group(1)); tag = m.group(2) or ""
    return v + (" \\checkmark" if "✓" in tag else (" (neg.)" if "负" in tag else ""))
rows = {}
for ln in log:
    m = re.match(r"^(gt|fp) (F1@0\.\d) (\S+): S1 (\S+) EO (\S+) 2D (\S+) \| (.*)$", ln)
    if not m:
        continue
    prot, met, grp, s1, eo, d2, rest = m.groups()
    sp = re.search(r"切碎 S1/EO/2D (\S+)", rest)
    rows[(prot, met, grp)] = [{"gt": "gt", "fp": "full pipeline"}[prot], "%s (%s)" % GRP[grp], met, "%s / %s / %s" % (s1, eo, d2),
                              diff(rest, "S1-EO"), diff(rest, "EO-2D"), diff(rest, "S1-2D"), sp.group(1) if sp else "--"]
val = {}
for ln in log:
    m = re.match(r"^val (F1@0\.\d) (\S+): S1 (\S+)\s+EO (\S+)\s+2D (\S+)\s*$", ln)
    if m:
        val[(m.group(1), m.group(2))] = (m.group(3), m.group(4), m.group(5))
body = []
for prot in ("gt", "fp"):
    for grp in ORDER:
        for met in ("F1@0.5", "F1@0.7"):
            body.append(" & ".join(rows[(prot, met, grp)]) + " \\\\")
vl = "; ".join("%s %s: S1 %s, EO %s, 2D %s" % (met, {"三视图": "three-view", "12套": "12 datasets", "13套": "13 datasets"}[g], *(x.replace("±", " $\\pm$ ") for x in val[(met, g)]))
               for met in ("F1@0.5", "F1@0.7") for g in ("三视图", "12套", "13套"))
cap = ("\\textbf{Encoder-only control (EO), five seeds, seed-paired with S1 and the 2D control.} EO is the 3D-stage encoder retraining on 3D patches without a decoder "
       "(design recorded before training, commit 331ec39). Macro F1 of S1 / EO / 2D control (mean of five seeds) and paired differences, mean $\\pm$ s.d.\\ over seed pairs; "
       "\\checkmark\\ confirmed (mean $>$ 2 s.d.\\ and $\\geq 0.01$); (neg.), negative with $|$mean$|$ $>$ 2 s.d.; split, fraction of ground-truth nuclei split, S1 / EO / 2D (F1@0.5 rows). "
       "Primary readout: the ten three-view datasets. On the three single-view datasets (Cellos, \\textit{Parhyale}, mesoSPIM) EO has no axial flow and cuts nuclei into slices, so these rows "
       "and the 12- and 13-dataset averages, which they dominate, do not measure decoder quality. Validation (gt protocol, mean $\\pm$ s.d.\\ over seeds): " + vl + ". "
       "Values as in the analysis log (four decimals).")
tex = ["%% GENERATED by scripts/make_supp_table_eo.py -- do not edit by hand.", "", "\\begin{table}[p]", "\\caption{" + cap + "}\\label{stab:eo}", "\\scriptsize",
       "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{@{}llllllll@{}}", "\\toprule",
       "Protocol & Datasets & Metric & S1 / EO / 2D & S1 $-$ EO & EO $-$ 2D & S1 $-$ 2D & Split \\\\", "\\midrule"] + body + ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
(here / "supp_tables_eo.tex").write_text("\n".join(tex), encoding="utf-8")
print("wrote supp_tables_eo.tex", len(body), "rows")
